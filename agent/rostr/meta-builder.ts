import type { SixthAgentBlueprint } from '../../src/types/monarch.ts';
import { ACP_VERSION } from './acp-protocol.ts';
import { MCP_PROTOCOL_VERSION, assertComposioNamespace } from './mcp-protocol.ts';

export function slugify(str: string): string {
  return (
    String(str || 'monarch-video-agent')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'monarch-video-agent'
  );
}

export function normalizeComposioServers(rawTools: string[] = []): string[] {
  return rawTools
    .map((t) => String(t).trim().toLowerCase())
    .filter(Boolean)
    .map((t) => (t.startsWith('composio-') ? t : `composio-${t}`));
}

export class SixthAgentMetaBuilder {
  compileBlueprint(input: {
    name: string;
    mission: string;
    audience?: string;
    tools?: string[];
    skills?: string[];
    provider?: string;
    model?: string;
    acpPeers?: string[];
    publicUrl?: string;
  }): SixthAgentBlueprint {
    const {
      name,
      mission,
      audience = 'Creators, Marketers, and Autonomous Studios',
      tools = ['github', 'google-drive', 'youtube', 'slack', 'notion'],
      skills = [
        'video-env-bootstrap',
        'pal-video-compiler',
        'artistic-director-suite',
        'editor-json-translator',
      ],
      provider = 'gemini',
      model = 'gemini-4-hydrogen',
      acpPeers = ['artistic-director', 'timeline-compiler', 'media-router'],
      publicUrl = 'https://monarch-video.workers.dev',
    } = input;

    const slug = slugify(name);
    const mcpServers = normalizeComposioServers(tools);
    assertComposioNamespace(mcpServers, true);

    const covenantMd = `# Agent Covenant: ${name}

## Objective
${mission}

## Target Audience
${audience}

## Capabilities
- Runs on Google ADK (@google/adk) + ROSTR 6-layer open-protocol stack (ContextEngine, PAL, Stateless MCP ${MCP_PROTOCOL_VERSION}, ACP ${ACP_VERSION}, NPAO Orchestration, 6th-Agent Scaffold).
- Executes 4-stage PAL intent extraction and artistic pre-production with human approval checkpoints.
- Routes external integrations exclusively through Composio MCP servers: ${mcpServers.join(', ')}.
- Loads registered skills: ${skills.join(', ')}.

## Operational Guardrails
- **Idempotency:** Mutating actions carry idempotency keys and replay cached outputs on duplicates.
- **Strict JSON Schema Validation:** All Timeline JSON and tool payloads validate strictly before rendering.
- **2026 Active Video Endpoints:** Never wire retired OpenAI Sora API endpoints; route generative clips to Veo 3.1, Runway Gen-4.5, Kling 4.0, or LTX-2.5.
- **Non-Destructive Execution:** Destructive root commands and schema drops are strictly halted.
`;

    const rostrConfigTs = `// ROSTR + Google ADK Agent Configuration — Generated by 6th Agent Meta-Builder
export default {
  name: ${JSON.stringify(name)},
  slug: ${JSON.stringify(slug)},
  mission: ${JSON.stringify(mission)},
  orchestrator: "google-adk",
  reasoning: {
    provider: ${JSON.stringify(provider)},
    model: ${JSON.stringify(model)},
    gatewayFallback: "vercel-ai-gateway"
  },
  mcpProtocolVersion: "${MCP_PROTOCOL_VERSION}",
  mcpServers: ${JSON.stringify(mcpServers, null, 2)},
  skills: ${JSON.stringify(skills, null, 2)},
  acp: {
    version: "${ACP_VERSION}",
    a2aCompatible: true,
    peers: ${JSON.stringify(acpPeers, null, 2)}
  },
  substrate: {
    provider: "cloudflare-context-engine",
    hybridRetrieval: true,
    ragDalCredibility: true
  }
};
`;

    const systemPromptTxt = `You are ${name}, an autonomous programmatic video director powered by Google ADK and the ROSTR 6-layer open-protocol architecture.
Mission: ${mission}
Target Audience: ${audience}

Tools registered:
- create_treatment, create_storyboard, create_script, create_agent_json
- select_voiceover, select_audio, select_animations, select_video

External Composio MCP connectors: ${mcpServers.join(', ')}.
Always run 4-stage PAL before drafting, pause for human approval before final renders, and patch Timeline JSON non-destructively.`;

    const agentCardJson = JSON.stringify(
      {
        schemaVersion: '1.0',
        protocols: [`acp/${ACP_VERSION}`, 'a2a/1.0', `mcp/${MCP_PROTOCOL_VERSION}`],
        orchestrator: '@google/adk',
        name,
        slug,
        description: mission,
        url: publicUrl,
        endpoints: {
          mcp: `${publicUrl}/mcp`,
          acpAgents: `${publicUrl}/acp/agents`,
          acpRuns: `${publicUrl}/acp/runs`,
        },
        mcpServers,
        skills,
        acpPeers,
      },
      null,
      2
    );

    const wranglerToml = `name = "${slug}"
main = "src/worker.ts"
compatibility_date = "2026-07-28"
compatibility_flags = ["nodejs_compat"]

[[durable_objects.bindings]]
name = "ROSTR_CONTEXT_ENGINE"
class_name = "RostrContextEngine"

[[migrations]]
tag = "v1"
new_sqlite_classes = ["RostrContextEngine"]

[[vectorize]]
binding = "ROSTR_VECTORIZE"
index_name = "${slug}-context-index"

[triggers]
crons = ["0 */6 * * *"]

[vars]
ROSTR_AGENT_NAME = "${name}"
ROSTR_LLM_PROVIDER = "${provider}"
ROSTR_LLM_MODEL = "${model}"
MCP_PROTOCOL_VERSION = "${MCP_PROTOCOL_VERSION}"
ACP_PROTOCOL_VERSION = "${ACP_VERSION}"
`;

    const agentManifestJson = JSON.stringify(
      {
        manifestVersion: '2026-07-28',
        agent: name,
        slug,
        backend: 'google-adk + rostr-6-layer',
        skills,
        registeredTools: [
          'create_treatment',
          'create_storyboard',
          'create_script',
          'create_agent_json',
          'select_voiceover',
          'select_audio',
          'select_animations',
          'select_video',
        ],
        openSourceLibraries: ['HyperFrames', 'OpenMontage', 'Remotion', 'GSAP 3', 'FFmpeg'],
        mcpServers,
        acpPeers,
      },
      null,
      2
    );

    return {
      slug,
      mcpServers,
      files: {
        'agent-manifest.json': agentManifestJson,
        'covenant.md': covenantMd,
        'rostr.config.ts': rostrConfigTs,
        'system_prompt.txt': systemPromptTxt,
        '.well-known/agent.json': agentCardJson,
        'wrangler.toml': wranglerToml,
      },
    };
  }
}
