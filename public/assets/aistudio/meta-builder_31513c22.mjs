/**
 * LAYER 6: The 6th Agent Meta-Builder
 *
 * Compiles plain-English agent requirements into a complete, protocol-compliant
 * ROSTR agent package:
 *   - covenant.md         (Identity, JTBD, Idempotency & Non-Destructive Guardrails)
 *   - rostr.config.ts     (Strictly enforces `composio-*` MCP prefixes + ACP peers)
 *   - system_prompt.txt   (Cloudflare Durable Object ContextEngine runtime prompt)
 *   - .well-known/agent.json (Offline ACP / A2A discovery manifest)
 *   - wrangler.toml       (Cloudflare Workers + Durable Objects + Vectorize binding)
 */

import { assertComposioNamespace, MCP_PROTOCOL_VERSION } from "../mcp/mcp-protocol.mjs";
import { ACP_VERSION } from "../acp/acp-protocol.mjs";

export function slugify(str) {
  return String(str || "rostr-agent")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "rostr-agent";
}

export function normalizeComposioServers(rawTools = []) {
  return rawTools
    .map((t) => String(t).trim().toLowerCase())
    .filter(Boolean)
    .map((t) => (t.startsWith("composio-") ? t : `composio-${t}`));
}

export class SixthAgentMetaBuilder {
  /**
   * Generate all production configuration files for a new ROSTR agent.
   */
  compileBlueprint({
    name,
    mission,
    audience = "Developers and Autonomous Teams",
    tools = ["github", "slack"],
    provider = "openai",
    model = "gpt-4.1-mini",
    acpPeers = [],
    publicUrl = "https://your-agent.workers.dev",
  }) {
    const slug = slugify(name);
    const mcpServers = normalizeComposioServers(tools);
    assertComposioNamespace(mcpServers, true);

    const covenantMd = `# Agent Covenant: ${name}

## Objective
${mission}

## Target Audience
${audience}

## Capabilities
- Operates on the 6-layer ROSTR open-protocol stack (Context Substrate, PAL Reasoning, MCP ${MCP_PROTOCOL_VERSION}, ACP ${ACP_VERSION}, NPAO Orchestration, Trace Observability).
- Executes tasks within the 5-stage PAL (Prompt Abstraction Layer) framework.
- Routes all external tool integrations strictly through Composio MCP servers: ${mcpServers.join(", ")}.
- Delegates specialized multi-agent handoffs over open ACP/A2A endpoints.

## Operational Guardrails
- **Idempotency:** Every mutating tool call must carry an idempotency key; duplicate requests replay cached results.
- **Strict JSON Parsing:** All reasoning outputs must conform to the PAL JSON decision contract.
- **Non-Destructive Execution:** Destructive root commands, schema drops, and unapproved bulk deletions are strictly blocked.
- **Observable Loops:** Every observation-action step emits structured OpenTelemetry-compatible trace spans.
`;

    const rostrConfigTs = `// ROSTR Agent Stack Configuration — Generated by 6th Agent Meta-Builder
export interface RostrConfig {
  name: string;
  slug: string;
  mission: string;
  reasoning: {
    provider: "openai" | "anthropic" | "gemini" | "ollama" | "mock";
    model: string;
  };
  mcpProtocolVersion: "${MCP_PROTOCOL_VERSION}";
  mcpServers: string[];
  acp: {
    version: "${ACP_VERSION}";
    a2aCompatible: boolean;
    peers: string[];
  };
  substrate: {
    provider: "cloudflare-context-engine";
    hybridRetrieval: boolean;
    ragDalCredibility: boolean;
  };
}

const config: RostrConfig = {
  name: ${JSON.stringify(name)},
  slug: ${JSON.stringify(slug)},
  mission: ${JSON.stringify(mission)},
  reasoning: {
    provider: ${JSON.stringify(provider)},
    model: ${JSON.stringify(model)},
  },
  mcpProtocolVersion: "${MCP_PROTOCOL_VERSION}",
  mcpServers: ${JSON.stringify(mcpServers, null, 2)},
  acp: {
    version: "${ACP_VERSION}",
    a2aCompatible: true,
    peers: ${JSON.stringify(acpPeers, null, 2)},
  },
  substrate: {
    provider: "cloudflare-context-engine",
    hybridRetrieval: true,
    ragDalCredibility: true,
  },
};

export default config;
`;

    const systemPromptTxt = `You are ${name}, a stateful autonomous agent running inside a Cloudflare Durable Object Context Engine.
Mission: ${mission}
Target Audience: ${audience}

You operate within the ROSTR 6-layer open-protocol architecture:
1. Pull fresh, credibility-scored hybrid context from the Context Substrate (RAG DAL).
2. Compile decisions through the 5-stage Prompt Abstraction Layer (PAL).
3. Invoke external tools exclusively through stateless MCP (${MCP_PROTOCOL_VERSION}) via Composio: ${mcpServers.join(", ")}.
4. Coordinate multi-agent handoffs over open ACP (${ACP_VERSION}) / A2A endpoints.
5. Follow the NPAO loop (Navigate, Prioritize, Allocate, Orchestrate) with full trace observability and non-destructive guardrails.
`;

    const agentCardJson = JSON.stringify(
      {
        schemaVersion: "1.0",
        protocols: [`acp/${ACP_VERSION}`, "a2a/1.0", `mcp/${MCP_PROTOCOL_VERSION}`],
        name,
        slug,
        description: mission,
        url: publicUrl,
        endpoints: {
          mcp: `${publicUrl}/mcp`,
          acpAgents: `${publicUrl}/acp/agents`,
          acpRuns: `${publicUrl}/acp/runs`,
        },
        mcpServers,
        acpPeers,
      },
      null,
      2
    );

    const wranglerToml = `name = "${slug}"
main = "src/worker.ts"
compatibility_date = "2026-07-28"
compatibility_flags = ["nodejs_compat"]

[[durable_objects.bindings]]
name = "ROSTR_CONTEXT_ENGINE"
class_name = "RostrContextEngine"

[[migrations]]
tag = "v1"
new_sqlite_classes = ["RostrContextEngine"]

[[vectorize]]
binding = "ROSTR_VECTORIZE"
index_name = "${slug}-context-index"

[triggers]
crons = ["0 */6 * * *"]

[vars]
ROSTR_AGENT_NAME = "${name}"
ROSTR_LLM_PROVIDER = "${provider}"
ROSTR_LLM_MODEL = "${model}"
MCP_PROTOCOL_VERSION = "${MCP_PROTOCOL_VERSION}"
ACP_PROTOCOL_VERSION = "${ACP_VERSION}"
`;

    return {
      slug,
      mcpServers,
      files: {
        "covenant.md": covenantMd,
        "rostr.config.ts": rostrConfigTs,
        "system_prompt.txt": systemPromptTxt,
        ".well-known/agent.json": agentCardJson,
        "wrangler.toml": wranglerToml,
      },
    };
  }
}
